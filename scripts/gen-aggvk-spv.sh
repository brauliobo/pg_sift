#!/usr/bin/env bash
# Compiles the compute shaders of src/agg/vk/shaders/ with glslc (--target-env=vulkan1.2 -O), shrinks them with spirv-opt (-O --strip-debug)
# and writes them as C arrays to src/agg/vk_spv.h, the file the VULKAN=1 build includes: a build needs no shader compiler. Run it, and commit
# the result, after editing a shader:  make gpu-shaders
#   scripts/gen-aggvk-spv.sh            write the header
#   scripts/gen-aggvk-spv.sh --check    fail when the header is not what the shaders give with this glslc and spirv-opt
# Any warning of glslc, spirv-opt or spirv-val is an error. The shaders need Vulkan 1.2 with 64-bit integer atomics and subgroup
# arithmetic (the device layer refuses a device that lacks them), so there is one variant of each.
set -euo pipefail
cd "$(dirname "$0")/.."

SHDIR=src/agg/vk/shaders
OUT=src/agg/vk_spv.h
NAMES="lz4 decode agg_ungrouped agg_dense agg_hash ht_compact topn agg_fast_ungrouped agg_fast_dense agg_fast_hash"
for t in glslc spirv-opt; do
	command -v "$t" >/dev/null || { echo "gen-aggvk-spv: $t is not installed" >&2; exit 2; }
done

tmp=$(mktemp -d "${TMPDIR:-/tmp}/sift-vk-spv.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
for n in $NAMES; do
	glslc -I "$SHDIR" --target-env=vulkan1.2 -O -Werror -o "$tmp/$n.raw" "$SHDIR/vk_$n.comp" 2> "$tmp/$n.log" || { cat "$tmp/$n.log" >&2; exit 1; }
	[ ! -s "$tmp/$n.log" ] || { cat "$tmp/$n.log" >&2; exit 1; }
	spirv-opt --target-env=vulkan1.2 -O --strip-debug -o "$tmp/$n.spv" "$tmp/$n.raw" 2> "$tmp/$n.opt.log"
	[ ! -s "$tmp/$n.opt.log" ] || { cat "$tmp/$n.opt.log" >&2; exit 1; }
	if command -v spirv-val >/dev/null; then
		spirv-val --target-env vulkan1.2 "$tmp/$n.spv" 2> "$tmp/$n.val.log" || { cat "$tmp/$n.val.log" >&2; exit 1; }
	fi
done

python3 - "$tmp" "$tmp/out.h" $NAMES <<'EOF'
import struct, sys
tmp, out, names = sys.argv[1], sys.argv[2], sys.argv[3:]
lines = ["/*",
         " * agg/vk_spv.h - the SPIR-V of the compute shaders of src/agg/vk/shaders/ (glslc --target-env=vulkan1.2 -O, spirv-opt -O --strip-debug),",
         " * generated by scripts/gen-aggvk-spv.sh; do not edit. Checked in so that a VULKAN=1 build needs no shader compiler.",
         " */",
         "#ifndef SIFT_AGGVK_SPV_H",
         "#define SIFT_AGGVK_SPV_H",
         "",
         "#include <stdint.h>",
         ""]
for n in names:
    data = open("%s/%s.spv" % (tmp, n), "rb").read()
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    lines.append("static const uint32_t sift_vk_spv_%s[%d] = {" % (n, len(words)))
    for i in range(0, len(words), 8):
        lines.append("\t" + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
    lines += ["};", ""]
lines += ["#endif\t\t\t\t\t\t\t/* SIFT_AGGVK_SPV_H */", ""]
open(out, "w").write("\n".join(lines))
EOF

if [ "${1:-}" = "--check" ]; then
	cmp -s "$tmp/out.h" "$OUT" || { echo "gen-aggvk-spv: $OUT differs from the shaders (run scripts/gen-aggvk-spv.sh)" >&2; exit 1; }
	echo "gen-aggvk-spv: ok"
else
	cp "$tmp/out.h" "$OUT"
	echo "gen-aggvk-spv: wrote $OUT"
	for n in $NAMES; do printf '  %-14s %7d bytes\n' "$n" "$(wc -c <"$tmp/$n.spv" | tr -d " ")"; done
fi
