#!/usr/bin/env bash
# The merge of the small overlays of a key-cut index is weighed against the scans the index has had, and those are a count in its metapage (core/reads.c), not the numscans of pg_stat: pg_stat_reset()
# leaves the decision as it was, and so do a clean restart and a crash. An index nobody has read is not merged.
. "$(dirname "$0")/lib.bash"
plan 7

node_init ov 82 "autovacuum = off
sift.async_maintenance = off
sift.test_col_partition_kb = 400
sift.col_auto_merge_wal_pct = 5"
node_start ov || bail "start failed"
sql ov "CREATE EXTENSION pg_sift" "SET max_parallel_maintenance_workers = 0" \
	"CREATE TABLE ov (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, dim_a_id int NOT NULL, kind_id int NOT NULL, amount float8 NOT NULL) WITH (autovacuum_enabled = off)" \
	"CREATE FUNCTION ov_rows(n int, keys int) RETURNS void LANGUAGE sql AS \$\$ INSERT INTO ov (dim_a_id, kind_id, amount) SELECT 1 + (random() * (keys - 1))::int, 1 + (random() * 6)::int, round((random() * 100)::numeric, 2) FROM generate_series(1, n) \$\$" \
	"SELECT ov_rows(60000, 3000)" "SET sift.col_unit_rows = 25" \
	"CREATE INDEX ov_idx ON ov USING sift_col (id, dim_a_id, kind_id, amount) WITH (key_cut = dim_a_id)" \
	"DELETE FROM ov WHERE id % 97 = 0" "UPDATE ov SET amount = amount + 1 WHERE id % 89 = 0" "VACUUM (FREEZE, ANALYZE) ov" \
	"SET sift.col_auto_merge = off" \
	"DO \$\$ BEGIN FOR i IN 1..12 LOOP PERFORM ov_rows(150, 12); PERFORM sift.col_promote('ov_idx'); COMMIT; END LOOP; END \$\$" \
	"VACUUM (FREEZE, ANALYZE, INDEX_CLEANUP off) ov" >/dev/null || bail "setup failed"

due() { sql ov "SELECT coalesce(sift.col_maintenance_due('ov_idx', true), 'not due')" | tail -n 1; }
segments() { sql ov "SELECT count(*) FROM sift.col_segments('ov_idx') WHERE kind = 'immutable'" | tail -n 1; }
# n requests of a key the overlays hold, in a session of their own that ends
requests() { sql ov "SET sift.agg_force = on" "SET max_parallel_workers_per_gather = 0" \
	"DO \$\$ BEGIN FOR i IN 1..$1 LOOP PERFORM kind_id, count(*), sum(amount) FROM ov WHERE dim_a_id = 1 + i % 12 GROUP BY kind_id; END LOOP; END \$\$" >/dev/null; }

S0=$(segments)
check "the overlays are several segments and no one has read the index: the merge is not worth its rows" test "$S0" -gt 3 -a "$(due)" == "not due"
requests 200
D=$(due)
check "200 requests in a session that ended make the merge due" test "$D" != "not due"
sql ov "SELECT pg_stat_force_next_flush()" "SELECT pg_stat_reset()" >/dev/null
check "pg_stat_reset() leaves the decision as it was" test "$(due)" == "$D"
check "and the numscans it zeroed were not what the decision read" test "$(sql ov "SELECT idx_scan FROM pg_stat_user_indexes WHERE indexrelname = 'ov_idx'" | tail -n 1)" -eq 0
wait_for "wal_flushed ov" 30
node_stop ov; node_start ov || bail "restart failed"
check "a clean restart leaves it as it was" test "$(due)" == "$D"
sleep 1
crash ov; node_start ov || bail "restart after the crash failed"
check "a crash leaves it as it was" test "$(due)" == "$D"
sql ov "SELECT sift.col_maintain('ov_idx')" >/dev/null
check "the merge the decision asks for takes the overlays" test "$(segments)" -lt "$S0"
finish
