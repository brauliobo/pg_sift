-- A Format 1 sift_table (the 5.x layout) rewritten by VACUUM FULL or CLUSTER while new relations take Format 2.0 comes out as Format 2.0 with every row;
-- a Format 2.0 table rewritten while new relations take Format 1 stays Format 2.0.
CREATE EXTENSION pg_sift;
SET sift.test_create_format1 = on;
CREATE TABLE r1 (id int PRIMARY KEY, g int NOT NULL, s text NOT NULL) USING sift_table;
CREATE TABLE r2 (id int PRIMARY KEY, g int NOT NULL, s text NOT NULL) USING sift_table;
INSERT INTO r1 SELECT i, i % 7, 'k' || i % 11 FROM generate_series(1, 3000) i;
INSERT INTO r2 SELECT i, i % 7, 'k' || i % 11 FROM generate_series(1, 3000) i;
DELETE FROM r1 WHERE id % 10 = 0;
DELETE FROM r2 WHERE id % 10 = 0;
VACUUM r1;
VACUUM r2;
SELECT r::text, f.major || '.' || f.minor AS format FROM unnest(ARRAY['r1', 'r2']::regclass[]) r, LATERAL sift.index_format(r) f ORDER BY 1;
SET sift.test_create_format1 = off;
VACUUM FULL r1;
CLUSTER r2 USING r2_pkey;
SELECT r::text, f.major || '.' || f.minor AS format FROM unnest(ARRAY['r1', 'r2']::regclass[]) r, LATERAL sift.index_format(r) f ORDER BY 1;
SELECT relation::text, format FROM sift.indexes WHERE relation IN ('r1'::regclass, 'r2'::regclass) ORDER BY 1;
SELECT count(*), sum(g), min(id), max(id) FROM r1;
SELECT count(*), sum(g), min(id), max(id) FROM r2;
INSERT INTO r1 VALUES (3001, 1, 'new');
SELECT count(*) FROM r1;
SET enable_seqscan = off;
SELECT count(*), sum(g) FROM r2 WHERE id BETWEEN 100 AND 200;
RESET enable_seqscan;
CREATE TABLE r3 (id int PRIMARY KEY, g int NOT NULL, s text NOT NULL) USING sift_table;
INSERT INTO r3 SELECT i, i % 7, 'k' || i % 11 FROM generate_series(1, 3000) i;
DELETE FROM r3 WHERE id % 10 = 0;
UPDATE r3 SET g = g + 100 WHERE id % 9 = 0;
SET sift.test_create_format1 = on;
VACUUM FULL r3;
SELECT f.major || '.' || f.minor AS format FROM sift.index_format('r3') f;
CLUSTER r3 USING r3_pkey;
SELECT f.major || '.' || f.minor AS format FROM sift.index_format('r3') f;
SELECT count(*), sum(g), min(id), max(id) FROM r3;
SET enable_seqscan = off;
SELECT count(*), sum(g) FROM r3 WHERE id BETWEEN 100 AND 200;
RESET enable_seqscan;
INSERT INTO r3 VALUES (3001, 1, 'new');
SELECT count(*) FROM r3;
RESET sift.test_create_format1;
DROP TABLE r1, r2, r3;
DROP EXTENSION pg_sift;
