-- Exact heap addresses, including a hint to a version rolled back at a savepoint.
CREATE EXTENSION pg_sift;
CREATE EXTENSION pg_sift_test;
SET client_min_messages = warning;
SHOW sift.eval_methods;
SET sift.eval_methods = 'unknown_method';
SET sift.eval_methods = 'latest_hint';
CREATE TABLE t (id int PRIMARY KEY, v int NOT NULL);
INSERT INTO t SELECT i, i FROM generate_series(1, 1200) i;
CREATE INDEX t_c ON t USING sift_col (id, v) WITH (track_updates = 'id');
CREATE TEMP TABLE expected (tid tid);
CREATE FUNCTION check_log() RETURNS boolean LANGUAGE sql AS $$
 SELECT coalesce((SELECT array_agg(tid ORDER BY tid) FROM expected), '{}') =
        coalesce((SELECT array_agg(DISTINCT tid ORDER BY tid) FROM sift._test_col_log_entries('t_c')
                  WHERE txid_status(xid::text::bigint) IS DISTINCT FROM 'aborted'), '{}') $$;
BEGIN;
INSERT INTO expected SELECT ctid FROM t;
UPDATE t SET v = v + 1;
INSERT INTO expected SELECT ctid FROM t;
UPDATE t SET v = v + 1;
SELECT check_log() AS exact_addresses;
SAVEPOINT s;
UPDATE t SET v = v + 100;
ROLLBACK TO s;
INSERT INTO expected SELECT ctid FROM t;
UPDATE t SET v = v + 1;
SELECT check_log() AS exact_after_abort;
COMMIT;
BEGIN;
INSERT INTO expected SELECT ctid FROM t;
UPDATE t SET v = v + 1;
SAVEPOINT s;
UPDATE t SET v = v + 100 WHERE id = 1;
ROLLBACK TO s;
INSERT INTO expected SELECT ctid FROM t WHERE id = 1;
UPDATE t SET v = v + 1 WHERE id = 1;
SELECT check_log() AS exact_hot_key;
COMMIT;
SET sift.enable_col = off;
SET sift.enable_agg = off;
CREATE TEMP TABLE by_heap AS SELECT md5(array_agg(ROW(id,v) ORDER BY id)::text) AS digest FROM t;
RESET sift.enable_col;
RESET sift.enable_agg;
SET enable_seqscan = off;
SELECT (SELECT digest FROM by_heap) = md5(array_agg(ROW(id,v) ORDER BY id)::text) AS same_heap FROM t;
RESET sift.eval_methods;
SELECT (SELECT digest FROM by_heap) = md5(array_agg(ROW(id,v) ORDER BY id)::text) AS same_off FROM t;
SET sift.eval_methods = 'latest_hint';
VACUUM t;
REINDEX INDEX t_c;
BEGIN;
TRUNCATE expected;
INSERT INTO expected SELECT ctid FROM t WHERE id = 1;
UPDATE t SET v = v + 1 WHERE id = 1;
INSERT INTO expected SELECT ctid FROM t WHERE id = 1;
UPDATE t SET v = v + 1 WHERE id = 1;
SELECT check_log() AS exact_after_reindex;
COMMIT;
DROP TABLE t;
DROP FUNCTION check_log();
DROP EXTENSION pg_sift_test;
DROP EXTENSION pg_sift;
