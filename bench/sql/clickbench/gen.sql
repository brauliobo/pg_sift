-- ClickBench-shaped synthetic `hits`: 105 canonical columns, deterministic (every draw is a hash of the row number), skewed so that every
-- query of Q0-Q42 returns rows at 10M. Writes CSV to stdout:   psql -X -qAt -v n=10000000 -f gen.sql > hits.csv
\set ON_ERROR_STOP on
CREATE FUNCTION pg_temp.u(bigint, int) RETURNS float8 LANGUAGE sql IMMUTABLE PARALLEL SAFE
  AS $$ SELECT (hashint8extended($1, $2::bigint) & 16777215)::float8 / 16777216 $$;
COPY (SELECT
  g::bigint AS WatchID,
  0::int2 AS JavaEnable,
  CASE WHEN pg_temp.u(g, 20) < 0.1 THEN '' WHEN pg_temp.u(g, 20) < 0.2 THEN 'Google Search ' WHEN pg_temp.u(g, 20) < 0.25 THEN 'Café ' ELSE 'Page ' END || floor(pg_temp.u(g, 21) * 5000)::int AS Title,
  0::int2 AS GoodEvent,
  date_trunc('second', timestamp '2013-07-01' + (g::float8 / :n) * 31 * interval '1 day') AS EventTime,
  (date_trunc('second', timestamp '2013-07-01' + (g::float8 / :n) * 31 * interval '1 day'))::date AS EventDate,
  CASE WHEN pg_temp.u(g, 1) < 0.12 THEN 62 ELSE 1 + floor(power(pg_temp.u(g, 2), 2) * 30000)::int END AS CounterID,
  1 + (hashint8extended(g, 2) & 1073741823)::int AS ClientIP,
  1 + floor(power(pg_temp.u(g, 3), 3) * 9000)::int AS RegionID,
  CASE WHEN pg_temp.u(g, 4) < 0.0002 THEN 435090932899640449 ELSE 1000003 * (1 + floor(greatest(:n / 10, 100) * power(pg_temp.u(g, 5), 2.2))::bigint) + 17 END AS UserID,
  0::int2 AS CounterClass,
  (pg_temp.u(g, 6) * 30)::int2 AS OS,
  (pg_temp.u(g, 7) * 20)::int2 AS UserAgent,
  'http://' || (ARRAY['www.google.com', 'google.com', 'maps.google.ru', 'example.com', 'news.example', 'shop.example', 'forum.example', 'blog.example'])[1 + floor(pg_temp.u(g, 8) * 8)::int] || '/' || floor(pg_temp.u(g, 9) * 100000)::int AS URL,
  CASE WHEN pg_temp.u(g, 10) < 0.5 THEN '' ELSE (ARRAY['http://', 'https://'])[1 + floor(pg_temp.u(g, 11) * 2)::int] || (ARRAY['example.com', 'www.example.com', 'news.example', 'www.google.com'])[1 + floor(pg_temp.u(g, 12) * 4)::int] || '/r' || floor(pg_temp.u(g, 13) * 1000)::int END AS Referer,
  (pg_temp.u(g, 14) < 0.1)::int::int2 AS IsRefresh,
  0::int2 AS RefererCategoryID,
  0 AS RefererRegionID,
  0::int2 AS URLCategoryID,
  0 AS URLRegionID,
  (ARRAY[1024, 1280, 1366, 1440, 1600, 1920, 2560])[1 + floor(pg_temp.u(g, 15) * 7)::int]::int2 AS ResolutionWidth,
  0::int2 AS ResolutionHeight,
  0::int2 AS ResolutionDepth,
  0::int2 AS FlashMajor,
  0::int2 AS FlashMinor,
  '' AS FlashMinor2,
  0::int2 AS NetMajor,
  0::int2 AS NetMinor,
  0::int2 AS UserAgentMajor,
  '' AS UserAgentMinor,
  0::int2 AS CookieEnable,
  0::int2 AS JavascriptEnable,
  0::int2 AS IsMobile,
  CASE WHEN pg_temp.u(g, 16) < 0.9 THEN 0 ELSE 1 + floor(pg_temp.u(g, 17) * 40)::int END::int2 AS MobilePhone,
  CASE WHEN pg_temp.u(g, 16) < 0.9 THEN '' ELSE 'model' || floor(pg_temp.u(g, 18) * 200)::int END AS MobilePhoneModel,
  '' AS Params,
  0 AS IPNetworkID,
  (ARRAY[-1, 1, 2, 3, 4, 5, 6, 7])[1 + floor(pg_temp.u(g, 19) * 8)::int]::int2 AS TraficSourceID,
  CASE WHEN pg_temp.u(g, 22) < 0.9 THEN 0 ELSE 1 + floor(pg_temp.u(g, 23) * 25)::int END::int2 AS SearchEngineID,
  CASE WHEN pg_temp.u(g, 22) < 0.9 THEN '' WHEN pg_temp.u(g, 24) < 0.05 THEN 'ключ ' || floor(pg_temp.u(g, 25) * 100)::int ELSE 'phrase ' || floor(power(pg_temp.u(g, 26), 3) * 50000)::int END AS SearchPhrase,
  CASE WHEN pg_temp.u(g, 27) < 0.9 THEN 0 ELSE 1 + floor(pg_temp.u(g, 28) * 20)::int END::int2 AS AdvEngineID,
  0::int2 AS IsArtifical,
  (ARRAY[0, 1024, 1280, 1366, 1920])[1 + floor(pg_temp.u(g, 29) * 5)::int]::int2 AS WindowClientWidth,
  (ARRAY[0, 600, 768, 1080])[1 + floor(pg_temp.u(g, 30) * 4)::int]::int2 AS WindowClientHeight,
  0::int2 AS ClientTimeZone,
  date_trunc('second', timestamp '2013-07-01' + (g::float8 / :n) * 31 * interval '1 day') - interval '60 seconds' AS ClientEventTime,
  0::int2 AS SilverlightVersion1,
  0::int2 AS SilverlightVersion2,
  0 AS SilverlightVersion3,
  0::int2 AS SilverlightVersion4,
  '' AS PageCharset,
  0 AS CodeVersion,
  (pg_temp.u(g, 31) < 0.2)::int::int2 AS IsLink,
  (pg_temp.u(g, 32) < 0.03)::int::int2 AS IsDownload,
  0::int2 AS IsNotBounce,
  0::bigint AS FUniqID,
  '' AS OriginalURL,
  0 AS HID,
  0::int2 AS IsOldCounter,
  0::int2 AS IsEvent,
  0::int2 AS IsParameter,
  (pg_temp.u(g, 33) < 0.05)::int::int2 AS DontCountHits,
  0::int2 AS WithHash,
  '0' AS HitColor,
  date_trunc('second', timestamp '2013-07-01' + (g::float8 / :n) * 31 * interval '1 day') + interval '3600 seconds' AS LocalEventTime,
  0::int2 AS Age,
  0::int2 AS Sex,
  0::int2 AS Income,
  0::int2 AS Interests,
  0::int2 AS Robotness,
  0 AS RemoteIP,
  0 AS WindowName,
  0 AS OpenerName,
  0::int2 AS HistoryLength,
  '' AS BrowserLanguage,
  '' AS BrowserCountry,
  '' AS SocialNetwork,
  '' AS SocialAction,
  0::int2 AS HTTPError,
  0 AS SendTiming,
  0 AS DNSTiming,
  0 AS ConnectTiming,
  0 AS ResponseStartTiming,
  0 AS ResponseEndTiming,
  0 AS FetchTiming,
  0::int2 AS SocialSourceNetworkID,
  '' AS SocialSourcePage,
  0::bigint AS ParamPrice,
  '' AS ParamOrderID,
  '' AS ParamCurrency,
  0::int2 AS ParamCurrencyID,
  '' AS OpenstatServiceName,
  '' AS OpenstatCampaignID,
  '' AS OpenstatAdID,
  '' AS OpenstatSourceID,
  '' AS UTMSource,
  '' AS UTMMedium,
  '' AS UTMCampaign,
  '' AS UTMContent,
  '' AS UTMTerm,
  '' AS FromTag,
  0::int2 AS HasGCLID,
  CASE WHEN pg_temp.u(g, 34) < 0.01 THEN 3594120000172545465 ELSE hashint8extended(g % 997, 7) END AS RefererHash,
  CASE WHEN pg_temp.u(g, 35) < 0.01 THEN 2868770270353813622 ELSE hashint8extended(g % 9973, 8) END AS URLHash,
  0 AS CLID
FROM generate_series(1, :n) g) TO STDOUT WITH (FORMAT csv);
