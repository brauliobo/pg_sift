-- a join to a large table whose only btree on the join column is a partial one (live links), probed for each key the scan meets when the join's own condition implies the predicate
-- label: {rows} * 1.5 events of 3,000 parents, a links table of 5 * {rows} rows (about 333 per parent, a fifth deleted), `JOIN links ON parent_id = e.foreign_id AND deleted_at IS NULL` for 10 parents of a range, btree on `(parent_id) WHERE deleted_at IS NULL`
-- ordered: yes
--@ setup
DO $do$ BEGIN
	IF to_regclass('pp_events') IS NULL THEN
		CREATE TABLE pp_events (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, foreign_id int NOT NULL, kind int NOT NULL, deleted_at timestamptz);
		INSERT INTO pp_events (foreign_id, kind) SELECT 1 + (random() * 2999)::int, g % 7 FROM generate_series(1, {rows} * 3 / 2) g;
		CREATE TABLE pp_links (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, parent_id int NOT NULL, label text NOT NULL, deleted_at timestamptz);
		INSERT INTO pp_links (parent_id, label, deleted_at) SELECT 1 + g % 3000, 'lbl_' || g / 3000 % 10, CASE WHEN g % 5 = 0 THEN timestamptz '2026-01-01' END FROM generate_series(1, {rows} * 5) g ORDER BY random();
		CREATE INDEX pp_links_live ON pp_links (parent_id) WHERE deleted_at IS NULL;
		CREATE INDEX pp_events_col ON pp_events USING sift_col (id, foreign_id, kind, deleted_at) WITH (key_cut = foreign_id);
	END IF;
END $do$;
VACUUM (FREEZE, ANALYZE) pp_events, pp_links
--@ pg
SELECT l.label, count(*) AS n, sum(e.kind) AS s FROM pp_events e JOIN pp_links l ON l.parent_id = e.foreign_id AND l.deleted_at IS NULL
WHERE e.foreign_id BETWEEN 100 AND 109 AND e.deleted_at IS NULL GROUP BY 1 ORDER BY 1
